#!/usr/bin/env python3
"""Generate offline UI content and Markdown from one reviewed English guide."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def outputs():
 data=json.loads((ROOT/'docs/guide.json').read_text());lines=['# '+data['title'],'','Version '+data['version']+' · Initial open-source release · [About and credits](../NOTICE.md)','','This guide is also available in the dashboard sidebar under **User Guide**. Installation prerequisites are in [INSTALLATION.md](INSTALLATION.md).','']
 for s in data['sections']:lines.append('- ['+s['title']+'](#'+s['id']+')')
 for s in data['sections']:
  lines+=['','<a id="'+s['id']+'"></a>','','## '+s['title'],'','**Where:** '+s['where'],'']
  for p in s['paragraphs']:lines += [p,'']
  for i,p in enumerate(s['steps'],1):lines.append(str(i)+'. '+p)
  if s['limit']:lines+=['','**Limit:** '+s['limit'],'']
 return {ROOT/'docs/USER_GUIDE.md':'\n'.join(lines)+'\n',ROOT/'lcpc/admin-ui/guide-content.js':'/* Generated by tools/build-guide.py. Edit docs/guide.json. */\n(()=>{const data='+json.dumps(data,ensure_ascii=True,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else window.LCPCGuideContent=data;})();\n'}
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for file,text in outputs().items():
  if args.check:
   if not file.exists() or file.read_text()!=text:raise SystemExit('Stale generated guide: '+str(file.relative_to(ROOT)))
  else:file.write_text(text)
